"""Расширенное тестирование алгоритма скидки — Полная версия ДЗ (Вариант 22: Автомобили)."""

from datetime import datetime
from discount import calculate_price_with_discount


def print_test_report(passed, total):
    """Задание 2. Функция вывода отчёта о тестировании."""
    print("\n" + "=" * 40)
    print("ОТЧЁТ О ТЕСТИРОВАНИИ")
    print(f"Пройдено: {passed} / {total}")
    if passed == total:
        print("Result: ✅ УСПЕХ")
    else:
        print("Result: ❌ ЕСТЬ ОШИБКИ")
    print("=" * 40)


def run_tests():
    test_cases = [
        # ======================================================================
        # БАЗОВЫЕ ТЕСТЫ (Из прошлых заданий - 11 штук)
        # ======================================================================
        (1, 1800000, datetime(2026, 10, 15), 1800000, "Honda — заказы есть в сентябре"),
        (2, 2800000, datetime(2026, 10, 15), 2800000, "Mazda — заказы есть в сентябре"),
        (3, 2000000, datetime(2026, 10, 15), 2000000, "Nissan — заказы есть in сентябре"),
        (4, 3500000, datetime(2026, 10, 15), 2625000, "VW Tiguan — заказов нет → скидка"),
        (5, 1500000, datetime(2026, 10, 15), 1125000, "Skoda — заказов нет → скидка"),
        
        (2, 2800000, datetime(2026, 11, 15), 2100000, "Mazda в октябре — заказов нет → скидка"),
        (1, 1800000, datetime(2026, 11, 15), 1350000, "Honda в октябре — заказов нет → скидка"),
        (4, 3500000, datetime(2026, 9, 1), 2625000, "VW Tiguan в августе — заказов нет → скидка"),

        (6, 1700000, datetime(2026, 10, 1), 1275000, "Renault в сентябре — заказов нет → скидка"),
        (7, 3000000, datetime(2026, 11, 20), 2250000, "Kia в октябре — заказов нет → скидка"),
        (3, 2000000, datetime(2026, 12, 5), 1500000, "Nissan в ноябре — заказов нет → скидка"),

        # ======================================================================
        # ЗАДАНИЕ 1. НОВЫЕ ГРАНИЧНЫЕ СЛУЧАИ (5 штук)
        # ======================================================================
        # Грань 1: Дата расчёта — 1-е число месяца (август 2026, заказов нет)
        (1, 1800000, datetime(2026, 9, 1), 1350000, "1-е число месяца — заказов нет → скидка"),
        
        # Грань 2: Дата расчёта — последний день месяца (сентябрь 2026, заказы есть)
        (1, 1800000, datetime(2026, 10, 31), 1800000, "Последний день месяца — заказы есть"),
        
        # Грань 3: Товар с нулевой ценой
        (4, 0, datetime(2026, 10, 15), 0, "Автомобиль с нулевой ценой → итог 0"),
        
        # Грань 4: Товар с отрицательным количеством (на складе)
        (5, 1500000, datetime(2026, 10, 15), 1125000, "Отрицательное количество -> скидка"),
        
        # Грань 5: Заказы в позапрошлом месяце (август), но не в предыдущем (сентябрь)
        (4, 3500000, datetime(2026, 10, 15), 2625000, "Заказы только в позапрошлом месяце -> скидка"),
    ]

    print("=" * 85)
    print("ПОЛНОЕ РАСШИРЕННОЕ ТЕСТИРОВАНИЕ АЛГОРИТМА СКИДКИ (ВАР 22: 16 ТЕСТ-КЕЙСОВ)")
    print("=" * 85)

    passed = 0
    for car_id, price, date, expected, comment in test_cases:
        result = calculate_price_with_discount(car_id, price, date)
        status = "✅" if result == expected else "❌"
        if result == expected:
            passed += 1
        print(f"{status} Авто ID {car_id} на {date.date()}: "
              f"{price} → {int(result)} (ожидалось {expected}) — {comment}")

    # Задание 2. Вывод итогового отчета
    print_test_report(passed, len(test_cases))


if __name__ == "__main__":
    run_tests()
