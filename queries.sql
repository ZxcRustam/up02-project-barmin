-- Задание 1. Самый дорогой товар (Автомобиль)
SELECT марка, модель, цена FROM Товар ORDER BY цена DESC LIMIT 1;

-- Задание 2. Самый дешёвый товар (Автомобиль)
SELECT марка, модель, цена FROM Товар ORDER BY цена ASC LIMIT 1;

-- Задание 3. Товары одной категории (Например, марки Honda)
SELECT марка, модель, цена FROM Товар WHERE марка = 'Honda';

-- Задание 4. Поиск по названию (Машины, в модели которых есть буква "а")
