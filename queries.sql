-- Задание 5. Все заказы
SELECT id, дата, клиент, товар_id, количество FROM Заказ;

-- Задание 6. Заказы конкретного клиента
SELECT * FROM Заказ WHERE клиент = 'Иванов Иван Иванович';

-- Задание 7. JOIN — заказы с названиями автомобилей
SELECT Заказ.дата, Заказ.клиент, Товар.марка, Товар.модель, Заказ.количество
FROM Заказ
    JOIN Товар ON Заказ.товар_id = Товар.id;

-- Задание 8. Общая сумма всех заказов
SELECT SUM(Товар.цена * Заказ.количество)
FROM Заказ
    JOIN Товар ON Заказ.товар_id = Товар.id;

-- Задание 9. Количество заказов по клиентам
SELECT клиент, COUNT(*) FROM Заказ GROUP BY клиент;

-- Задание 10. Свой запрос
-- Что хочу получить: Вывести машины, у которых остаток на складе больше 2 штук
